import openpyxl
from openpyxl.styles import Font, Alignment, PatternFill, Border, Side
from openpyxl.utils import get_column_letter

wb = openpyxl.Workbook()

# ========== Common Styles ==========
header_font = Font(name='微软雅黑', bold=True, size=11, color='FFFFFF')
header_fill = PatternFill(start_color='1E3A8A', end_color='1E3A8A', fill_type='solid')
header_alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
cell_font = Font(name='微软雅黑', size=10)
cell_alignment = Alignment(horizontal='center', vertical='center')
cell_alignment_left = Alignment(horizontal='left', vertical='center')
thin_border = Border(
    left=Side(style='thin', color='D1D5DB'),
    right=Side(style='thin', color='D1D5DB'),
    top=Side(style='thin', color='D1D5DB'),
    bottom=Side(style='thin', color='D1D5DB'),
)
even_fill = PatternFill(start_color='F5F7FA', end_color='F5F7FA', fill_type='solid')

def style_sheet(ws, headers, col_widths):
    for col_idx, (header, width) in enumerate(zip(headers, col_widths), 1):
        cell = ws.cell(row=1, column=col_idx, value=header)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = header_alignment
        cell.border = thin_border
        ws.column_dimensions[get_column_letter(col_idx)].width = width
    ws.auto_filter.ref = ws.dimensions
    ws.freeze_panes = 'A2'
    ws.sheet_properties.tabColor = '1E3A8A'

def style_data_rows(ws, start_row, end_row, num_cols, left_cols=None):
    if left_cols is None:
        left_cols = set()
    for row in range(start_row, end_row + 1):
        for col in range(1, num_cols + 1):
            cell = ws.cell(row=row, column=col)
            cell.font = cell_font
            cell.border = thin_border
            if col in left_cols:
                cell.alignment = cell_alignment_left
            else:
                cell.alignment = cell_alignment
        if row % 2 == 0:
            for col in range(1, num_cols + 1):
                ws.cell(row=row, column=col).fill = even_fill

